"""Analyze the scale experiment: speed (GAGP GPU vs ASGP-1T and vs the GAGP CPU
reference), bitwise engine parity, and quality on the held-out test split.

usage: analyze.py OUTDIR
Writes OUTDIR/results.json, OUTDIR/results.md and OUTDIR/cells.csv."""
import csv, json, math, random, sys
from collections import defaultdict
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent)); import common as c

OUT = Path(sys.argv[1]); OUT.mkdir(parents=True, exist_ok=True)
rec = {}
for kind in ("gpu", "cpu", "gpugen"):
    p = c.ROOT / f"record_{kind}.json"
    if p.exists(): rec.update(c.read(p))
judge = c.read(c.ROOT / "judge.json") if (c.ROOT / "judge.json").exists() else {}
ok = lambda k: rec.get(k, {}).get("code") == 0
key = lambda arm, t, s, p: f"{arm}/{t}.s{s}.p{p}"


def geo(xs): return math.exp(sum(map(math.log, xs)) / len(xs)) if xs else None


def strip(x):
    if isinstance(x, dict): return {k: strip(v) for k, v in x.items() if not k.endswith("_ms")}
    if isinstance(x, list): return [strip(v) for v in x]
    return x


def same_search(a, b):
    """Champion export byte-identical and history identical apart from timing fields."""
    ra, rb = rec[a], rec[b]
    return (Path(ra["export"]).read_bytes() == Path(rb["export"]).read_bytes() and
            strip(c.read(ra["history"])) == strip(c.read(rb["history"])))


def binom_two_sided(b, n):
    if n == 0: return 1.0
    k = min(b, n - b)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def solved(name, split="test"):
    j = judge.get(name, {}).get(split)
    return None if not j or j.get("cases") is None else int(j["exact"] == j["cases"])


res = {"tasks": c.TASKS, "pops": c.POPS, "seeds": c.SEEDS}
md = ["# Final scale experiment: results", "",
      "Generated by `tools/analyze.py`. Times are `evolve_wall_ms` (search only), unprofiled.", ""]

# ---------------------------------------------------------------- speed vs ASGP-1T
md += ["## Speed: ASGP-1T time / GAGP GPU time (G64)", "",
       "| P | cells | tasks | geo mean (task geo over seeds) | sum ratio | min task | max task | GAGP total s | ASGP total s |",
       "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
speed = {}
per_task_speed = defaultdict(dict)
for p in c.POPS:
    cells = [(t, s) for t in c.TASKS for s in c.SEEDS if ok(key("gagp", t, s, p)) and ok(key("asgp", t, s, p))]
    by_task = defaultdict(list)
    for t, s in cells: by_task[t].append(rec[key("asgp", t, s, p)]["search_s"] / rec[key("gagp", t, s, p)]["search_s"])
    task_ratio = {t: geo(v) for t, v in by_task.items()}
    for t, v in task_ratio.items(): per_task_speed[t][p] = v
    sg = sum(rec[key("gagp", t, s, p)]["search_s"] for t, s in cells)
    sa = sum(rec[key("asgp", t, s, p)]["search_s"] for t, s in cells)
    speed[p] = dict(cells=len(cells), tasks=len(task_ratio), geo=geo(list(task_ratio.values())),
                    sum_ratio=sa / sg if sg else None, gagp_s=sg, asgp_s=sa,
                    min=min(task_ratio.items(), key=lambda x: x[1]) if task_ratio else None,
                    max=max(task_ratio.items(), key=lambda x: x[1]) if task_ratio else None)
    if cells:
        d = speed[p]
        md.append(f"| {p} | {d['cells']} | {d['tasks']} | {d['geo']:.2f}x | {d['sum_ratio']:.2f}x | "
                  f"{d['min'][0]} {d['min'][1]:.2f}x | {d['max'][0]} {d['max'][1]:.2f}x | {sg:.0f} | {sa:.0f} |")
res["speed_vs_asgp"] = speed

# scaling of each engine's own time with P (same task and seed in all pops)
md += ["", "## Time growth with population (geo mean over task/seed cells present at all P)", "",
       "| engine | T(4096)/T(1024) | T(16384)/T(1024) | cells |", "| --- | ---: | ---: | ---: |"]
growth = {}
for arm in ("gagp", "asgp"):
    cells = [(t, s) for t in c.TASKS for s in c.SEEDS if all(ok(key(arm, t, s, p)) for p in c.POPS)]
    g = {p: geo([rec[key(arm, t, s, p)]["search_s"] / rec[key(arm, t, s, 1024)]["search_s"] for t, s in cells]) for p in (4096, 16384)}
    growth[arm] = dict(cells=len(cells), **{str(p): v for p, v in g.items()})
    if cells: md.append(f"| {arm} | {g[4096]:.2f} | {g[16384]:.2f} | {len(cells)} |")
res["time_growth"] = growth

# ---------------------------------------------------------------- CPU reference
md += ["", "## GAGP CPU reference vs GAGP GPU (seed 1)", "",
       "| comparison | P | G | tasks | geo speedup | sum speedup | identical searches |",
       "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
cpuref = {}
for arm, gpu_arm, pops, gens in (("cpuref", "gagp", (1024,), 64), ("cpuref_g8", "gagp_g8", (4096, 16384), 8)):
    for p in pops:
        ts = [t for t in c.TASKS if ok(key(arm, t, 1, p)) and ok(key(gpu_arm, t, 1, p))]
        r = [rec[key(arm, t, 1, p)]["search_s"] / rec[key(gpu_arm, t, 1, p)]["search_s"] for t in ts]
        same = [t for t in ts if same_search(key(arm, t, 1, p), key(gpu_arm, t, 1, p))]
        sc = sum(rec[key(arm, t, 1, p)]["search_s"] for t in ts); sg = sum(rec[key(gpu_arm, t, 1, p)]["search_s"] for t in ts)
        cpuref[f"{arm}.p{p}"] = dict(tasks=len(ts), geo=geo(r), sum_ratio=sc / sg if sg else None, identical=len(same),
                                     differing=[t for t in ts if t not in same], per_task=dict(zip(ts, r)))
        if ts: md.append(f"| CPU reference / GPU | {p} | {gens} | {len(ts)} | {geo(r):.2f}x | {sc / sg:.2f}x | {len(same)}/{len(ts)} |")
# G8 GPU runs must also equal the first part of nothing else; G64 vs G8 prefix of the same run is a free determinism check
prefix = []
for p in (4096, 16384):
    for t in c.TASKS:
        a, b = key("gagp", t, 1, p), key("gagp_g8", t, 1, p)
        if ok(a) and ok(b):
            ha, hb = strip(c.read(rec[a]["history"]))["history"], strip(c.read(rec[b]["history"]))["history"]
            prefix.append(ha[:len(hb)] == hb)
res["cpu_reference"] = cpuref
res["g8_history_is_prefix_of_g64"] = dict(checked=len(prefix), equal=sum(prefix))
md += ["", f"G8 GPU history equals the first 8 generations of the G64 GPU run: {sum(prefix)}/{len(prefix)} (seed 1, P4096/16384)."]

# ---------------------------------------------------------------- quality
md += ["", "## Quality: runs solving every held-out test case", "",
       "| P | paired runs | GAGP solved | ASGP solved | GAGP only | ASGP only | McNemar p | diff (pp) | 95% task-bootstrap CI (pp) |",
       "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
quality = {}
rng = random.Random(20261103)
for split in ("test", "train"):
    quality[split] = {}
    for p in c.POPS:
        pairs = [(t, s, solved(key("gagp", t, s, p), split), solved(key("asgp", t, s, p), split))
                 for t in c.TASKS for s in c.SEEDS]
        pairs = [x for x in pairs if x[2] is not None and x[3] is not None]
        if not pairs: continue
        g = sum(x[2] for x in pairs); a = sum(x[3] for x in pairs)
        b = sum(1 for x in pairs if x[2] and not x[3]); cc = sum(1 for x in pairs if x[3] and not x[2])
        by_task = defaultdict(list)
        for t, s, x, y in pairs: by_task[t].append(x - y)
        tasks = list(by_task); boots = []
        for _ in range(10000):
            draw = [by_task[rng.choice(tasks)] for _ in tasks]
            boots.append(100 * sum(map(sum, draw)) / sum(map(len, draw)))
        boots.sort()
        q = dict(pairs=len(pairs), gagp=g, asgp=a, gagp_only=b, asgp_only=cc, p=binom_two_sided(b, b + cc),
                 diff_pp=100 * (g - a) / len(pairs), ci=[boots[249], boots[9749]],
                 per_task={t: dict(gagp=sum(x[2] for x in pairs if x[0] == t), asgp=sum(x[3] for x in pairs if x[0] == t),
                                   n=sum(1 for x in pairs if x[0] == t)) for t in tasks})
        quality[split][p] = q
        if split == "test":
            md.append(f"| {p} | {len(pairs)} | {g} | {a} | {b} | {cc} | {q['p']:.3g} | {q['diff_pp']:+.1f} | [{q['ci'][0]:+.1f}, {q['ci'][1]:+.1f}] |")
res["quality"] = quality
md += ["", "Train-split solves (all 1024 training cases exact):", "",
       "| P | paired runs | GAGP | ASGP | McNemar p |", "| ---: | ---: | ---: | ---: | ---: |"]
for p, q in quality["train"].items(): md.append(f"| {p} | {q['pairs']} | {q['gagp']} | {q['asgp']} | {q['p']:.3g} |")

# GAGP at larger P vs ASGP at P1024 (time and quality)
md += ["", "## Larger GAGP population vs ASGP-1T at P1024", "",
       "| GAGP P | paired runs | GAGP solved | ASGP P1024 solved | McNemar p | GAGP total s | ASGP P1024 total s |",
       "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
cross = {}
for p in c.POPS:
    pairs = [(t, s) for t in c.TASKS for s in c.SEEDS
             if solved(key("gagp", t, s, p)) is not None and solved(key("asgp", t, s, 1024)) is not None]
    if not pairs: continue
    g = [solved(key("gagp", t, s, p)) for t, s in pairs]; a = [solved(key("asgp", t, s, 1024)) for t, s in pairs]
    b = sum(1 for x, y in zip(g, a) if x and not y); cc = sum(1 for x, y in zip(g, a) if y and not x)
    tg = sum(rec[key("gagp", t, s, p)]["search_s"] for t, s in pairs); ta = sum(rec[key("asgp", t, s, 1024)]["search_s"] for t, s in pairs)
    cross[p] = dict(pairs=len(pairs), gagp=sum(g), asgp=sum(a), p=binom_two_sided(b, b + cc), gagp_s=tg, asgp_s=ta)
    md.append(f"| {p} | {len(pairs)} | {sum(g)} | {sum(a)} | {cross[p]['p']:.3g} | {tg:.0f} | {ta:.0f} |")
res["gagp_p_vs_asgp_p1024"] = cross

# steady state (final profile) vs the generational schedule, both GPU
md += ["", "## Schedule ablation: steady state B = P (final) vs generational, GAGP GPU", "",
       "| P | paired runs | time generational / steady (geo) | steady solved | generational solved | McNemar p | diff (pp) | 95% task-bootstrap CI (pp) |",
       "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
ablation = {}
for p in c.POPS:
    cells = [(t, s) for t in c.TASKS for s in c.SEEDS if ok(key("gagp", t, s, p)) and ok(key("gagp_gen", t, s, p))]
    if not cells: continue
    by_task = defaultdict(list)
    for t, s in cells: by_task[t].append(rec[key("gagp_gen", t, s, p)]["search_s"] / rec[key("gagp", t, s, p)]["search_s"])
    sp = geo([geo(v) for v in by_task.values()])
    pairs = [(t, s, solved(key("gagp", t, s, p)), solved(key("gagp_gen", t, s, p))) for t, s in cells]
    pairs = [x for x in pairs if x[2] is not None and x[3] is not None]
    g = sum(x[2] for x in pairs); a = sum(x[3] for x in pairs)
    b = sum(1 for x in pairs if x[2] and not x[3]); cc = sum(1 for x in pairs if x[3] and not x[2])
    diffs = defaultdict(list)
    for t, s, x, y in pairs: diffs[t].append(x - y)
    tasks = list(diffs); boots = []
    for _ in range(10000):
        draw = [diffs[rng.choice(tasks)] for _ in tasks]
        boots.append(100 * sum(map(sum, draw)) / sum(map(len, draw)))
    boots.sort()
    ablation[p] = dict(cells=len(cells), speed_geo=sp, steady=g, generational=a, steady_only=b, generational_only=cc,
                       p=binom_two_sided(b, b + cc), diff_pp=100 * (g - a) / len(pairs), ci=[boots[249], boots[9749]],
                       steady_s=sum(rec[key("gagp", t, s, p)]["search_s"] for t, s in cells),
                       generational_s=sum(rec[key("gagp_gen", t, s, p)]["search_s"] for t, s in cells))
    q = ablation[p]
    md.append(f"| {p} | {len(pairs)} | {sp:.3f}x | {g} | {a} | {q['p']:.3g} | {q['diff_pp']:+.1f} | [{q['ci'][0]:+.1f}, {q['ci'][1]:+.1f}] |")
res["schedule_ablation"] = ablation

# per-task table
md += ["", "## Per task (geo speedup over seeds; test solves out of seeds)", "",
       "| task | " + " | ".join(f"speedup P{p}" for p in c.POPS) + " | " +
       " | ".join(f"GAGP/ASGP solved P{p}" for p in c.POPS) + " |",
       "| --- |" + " ---: |" * (2 * len(c.POPS))]
for t in c.TASKS:
    sp = [f"{per_task_speed[t][p]:.1f}x" if p in per_task_speed[t] else "-" for p in c.POPS]
    qs = []
    for p in c.POPS:
        q = quality["test"].get(p, {}).get("per_task", {}).get(t)
        qs.append(f"{q['gagp']}/{q['asgp']} of {q['n']}" if q else "-")
    md.append(f"| {t} | " + " | ".join(sp + qs) + " |")

# failures
fails = sorted(k for k, v in rec.items() if v.get("code") != 0)
res["failed_runs"] = {k: str(rec[k].get("code")) for k in fails}
md += ["", f"Failed or timed-out runs: {len(fails)}" + ("" if not fails else ": " + ", ".join(fails[:40]))]

with open(OUT / "cells.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["arm", "task", "seed", "pop", "code", "search_s", "final_best", "test_exact", "test_cases", "train_exact", "train_cases"])
    for k in sorted(rec):
        v = rec[k]; j = judge.get(k, {})
        w.writerow([v["arm"], v["task"], v["seed"], v["pop"], v["code"], round(v.get("search_s", 0), 4), v.get("final_best"),
                    j.get("test", {}).get("exact"), j.get("test", {}).get("cases"), j.get("train", {}).get("exact"), j.get("train", {}).get("cases")])
c.save(OUT / "results.json", res)
(OUT / "results.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
